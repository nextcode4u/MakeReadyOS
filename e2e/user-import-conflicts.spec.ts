import { expect, test, type Page } from "@playwright/test";

test("keep conflicting units local imports all other availability rows", async ({ page }, info) => {
  test.skip(!process.env.COMPOSE_PROJECT_NAME?.startsWith("makereadyos-e2e-"), "Disposable demo environment required");
  test.setTimeout(120000);
  const prefix = info.project.name === "user-mobile" ? "KEEP-M" : "KEEP-D";
  const localStatus = info.project.name === "user-mobile" ? "VACANT NOT LEASED NOT READY" : "VACANT NOT LEASED READY";
  const reportStatus = info.project.name === "user-mobile" ? "VACANT NOT LEASED READY" : "VACANT NOT LEASED NOT READY";
  const kept = `${prefix}-1`, changed = `${prefix}-2`, added = `${prefix}-3`;
  const day = (offset: number) => { const date = new Date(); date.setDate(date.getDate() + offset); return date.toISOString().slice(0, 10); };
  const header = "unit,vacancyStatus,moveOutDate,reportDate";
  const tab = async (target: Page, name: string) => {
    if (await target.getByTestId("mobile-views-toggle").isVisible()) await target.getByTestId("mobile-views-toggle").click();
    await target.getByRole("tab", { name, exact: true }).click();
  };
  const openUnit = async (unit: string) => {
    await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(unit);
    await page.getByTestId(`${info.project.name === "user-mobile" ? "mobile" : "item"}-details-${unit.toLowerCase()}`).click();
    await page.getByTestId("drawer-pane-all").click();
  };
  await page.goto("/");
  await page.getByTestId("login-email").fill(process.env.ADMIN_EMAIL!);
  await page.getByTestId("login-password").fill(process.env.ADMIN_PASSWORD!);
  await page.getByRole("button", { name: /sign in/i }).click();
  await page.getByTestId("property-filter").selectOption({ label: "DG · Demo Gardens" });
  await tab(page, "Availability & Units");
  await page.getByTestId("availability-import-csv").fill(`${header}\n${kept},${localStatus},,${day(1)}\n${changed},NTV NOT LEASED,${day(2)},${day(1)}`);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-submit").click();
  await expect(page.getByTestId("availability-import-last-import")).toContainText("2 turns created");
  await tab(page, "Table");
  await openUnit(kept);
  await page.getByTestId("drawer-notes").fill("Keep this local inspection context.");
  await page.getByTestId("drawer-notes").press("Tab");
  await page.getByTestId("item-drawer-close").click();
  await tab(page, "Availability & Units");
  const report = `${header}\n${kept},${reportStatus},,${day(-1)}\n${changed},NTV NOT LEASED,${day(7)},${day(1)}\n${added},NTV NOT LEASED,${day(9)},${day(1)}`;
  await page.getByTestId("availability-import-csv").fill(report);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-submit").click();
  await expect(page.getByTestId("availability-import-conflicts")).toContainText(kept);
  await page.getByRole("button", { name: "Cancel import", exact: true }).click();
  await expect(page.getByTestId("availability-import-conflicts")).toBeHidden();
  await expect(page.getByTestId("availability-import-csv")).toHaveValue(report);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-submit").click();
  await expect(page.getByTestId("availability-import-conflicts")).toContainText(kept);
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByTestId("availability-import-keep-local").click();
  await expect(page.getByTestId("availability-import-csv")).toHaveValue(report);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-keep-local").click();
  await expect(page.getByTestId("availability-import-preserved")).toContainText(kept);
  await expect(page.getByTestId("availability-import-last-import")).toContainText("1 turns created, 1 turns updated");
  await page.reload();
  await tab(page, "Table");
  await openUnit(kept);
  await expect(page.getByTestId("drawer-field-vacancyStatus")).toHaveValue(localStatus);
  await expect(page.getByTestId("drawer-notes")).toHaveValue("Keep this local inspection context.");
  await page.getByTestId("item-drawer-close").click();
  await openUnit(changed);
  await expect(page.getByTestId("drawer-field-moveOutDate")).toHaveValue(day(7));
  await page.getByTestId("item-drawer-close").click();
  await openUnit(added);
  await expect(page.getByTestId("drawer-field-moveOutDate")).toHaveValue(day(9));
});
