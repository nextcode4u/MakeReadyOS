import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";

test("report wording Markdown survives saving and renders in preview and PDF", async ({ page }, info) => {
  test.skip(!process.env.COMPOSE_PROJECT_NAME?.startsWith("makereadyos-e2e-"), "Disposable demo environment required");
  test.setTimeout(120000);
  await page.goto("/");
  await page.getByTestId("login-email").fill(process.env.ADMIN_EMAIL!);
  await page.getByTestId("login-password").fill(process.env.ADMIN_PASSWORD!);
  await page.getByRole("button", { name: /sign in/i }).click();
  await page.getByRole("button", { name: "Open details for DG-101", exact: true }).click();
  await page.getByTestId("drawer-pane-all").click();
  await page.getByRole("button", { name: "Inspection details / report", exact: true }).click();
  const report = page.getByTestId("final-report-editor");
  const emojis = "\u{1F3E0} \u{1F511} \u{1F43E} \u{1F697} \u{1F44B}\u{1F3FD}";
  const introduction = `## Welcome home\n\n${emojis}\n\n**Enjoy your home** and *contact the office*.\nOffice hours below (${info.project.name}).`;
  const footer = `## Community reminders\n\n${emojis}\n\n- Designated parking only\n- Keep pets leashed\n\n[Resident portal](https://example.com)\n\n` + Array.from({ length: 90 }, (_, i) => `Resident guidance line ${i + 1}.`).join("\n") + "\n\n**End of welcome information**";
  await report.getByRole("textbox", { name: "Introduction", exact: true }).fill(introduction);
  await report.getByRole("textbox", { name: "Resident footer", exact: true }).fill(footer);
  await report.getByRole("button", { name: "Save report settings", exact: true }).click();
  await expect(report.getByRole("button", { name: "Save report settings", exact: true })).toBeDisabled();
  await report.getByTestId("final-report-preview").click();
  const frame = report.frameLocator("iframe");
  await expect(frame.getByRole("heading", { name: "Welcome home", exact: true })).toBeVisible();
  await expect(frame.locator("strong").filter({ hasText: "Enjoy your home" })).toHaveCount(1);
  await expect(frame.getByRole("link", { name: "Resident portal" })).toHaveAttribute("href", "https://example.com");
  await expect(frame.locator("li").filter({ hasText: "Keep pets leashed" })).toHaveCount(1);
  await report.getByText("Draft tools / not the resident copy", { exact: true }).click();
  const download = page.waitForEvent("download");
  await report.getByTestId("final-report-pdf").click();
  const file = await download;
  const path = info.outputPath("markdown-report.pdf");
  await file.saveAs(path);
  expect(await file.failure()).toBeNull();
  const text = execFileSync("pdftotext", [path, "-"], { encoding: "utf8" });
  expect(text).toContain("Welcome home");
  for (const emoji of ["\u{1F3E0}", "\u{1F511}", "\u{1F43E}", "\u{1F697}"]) expect(text.split(emoji).length).toBeGreaterThanOrEqual(3);
  // Rasterize the actual server PDF too; preview fonts come from the user's device.
  execFileSync("pdftoppm", ["-f", "1", "-singlefile", "-scale-to", "1600", "-png", path, info.outputPath("emoji-export")]);
  expect(text).toContain("End of welcome information");
  expect(text).not.toContain("**Enjoy");
  expect(text).not.toContain("## Community");
  expect(text.split("\f").filter(part => part.trim()).length).toBeGreaterThan(1);
  page.once("dialog", dialog => dialog.accept());
  await page.reload();
  await page.getByTestId("drawer-pane-all").click();
  await page.getByRole("button", { name: "Inspection details / report", exact: true }).click();
  await expect(report.getByRole("textbox", { name: "Introduction", exact: true })).toHaveValue(introduction);
  await expect(report.getByRole("textbox", { name: "Resident footer", exact: true })).toHaveValue(footer);
});
