import { expect, test } from "@playwright/test";

test("simple project input saves product link and total and preserves them in backups", async ({ page }, testInfo) => {
  test.setTimeout(120000);
  await page.goto("/");
  await page.getByTestId("login-email").fill(process.env.ADMIN_EMAIL || "admin@example.com");
  await page.getByTestId("login-password").fill(process.env.ADMIN_PASSWORD || "ChangeThisAdmin!23456");
  await page.getByTestId("login-submit").click();
  await expect(page.getByTestId("property-filter")).toBeVisible();
  const session = await (await page.request.get("/api/auth/me")).json();
  const headers = { "x-csrf-token": session.csrfToken };
  const response = await page.request.post("/api/operations/properties", { headers, data: { code: `SIMPLE${Date.now()}`, name: "Simple entry fixture" } });
  expect(response.ok()).toBeTruthy();
  const { property } = await response.json();
  await page.reload();
  await page.getByTestId("property-filter").selectOption(property.id);
  await page.getByTestId("module-rail-projects").click();
  await page.getByTestId("projects-quick-capture-open").click();
  await page.getByTestId("projects-quick-capture-title").fill("Dog stations");
  await page.getByTestId("projects-product-url").fill("https://www.amazon.com/dp/EXAMPLE");
  await page.getByTestId("projects-estimated-total").fill("299.95");
  const created = page.waitForResponse(r => r.url().endsWith("/api/projects/records") && r.request().method() === "POST");
  await page.getByTestId("projects-quick-capture-save").click();
  const savedResponse = await created;
  expect(savedResponse.ok(), await savedResponse.text()).toBeTruthy();
  const { record } = await savedResponse.json();
  expect(record.productUrl).toBe("https://www.amazon.com/dp/EXAMPLE");
  expect(record.estimatedCost).toBe(299.95);
  expect(record.actualCost).toBeNull();
  await page.getByRole("button", { name: "View Record", exact: true }).click();
  await expect(page.getByRole("link", { name: "View product / vendor" })).toHaveAttribute("href", record.productUrl);
  await page.getByText("Edit title, link & total", { exact: true }).click();
  const basics = page.locator("form").filter({ has: page.getByRole("button", { name: "Save basics", exact: true }) });
  await basics.getByLabel("Estimated total ($)", { exact: true }).fill("349.50");
  await basics.getByRole("button", { name: "Save basics", exact: true }).click();
  await expect(basics).toContainText("Basics saved.");
  const stored = await (await page.request.get(`/api/projects/records/${record.id}`)).json();
  expect(stored.record.estimatedCost).toBe(349.5);
  const exported = await (await page.request.get("/api/admin/export")).json();
  const copy = exported.data.projectRecords.find((r: any) => r.title === "Dog stations");
  expect(copy.productUrl).toBe(record.productUrl);
  const backup = { ...exported, data: { ...Object.fromEntries(Object.keys(exported.data).map(key => [key, []])), projectRecords: [{ ...copy, title: "Restored dog stations", portableKey: "restored-dog-stations" }] } };
  const restored = await page.request.post("/api/admin/import", { headers, data: { backup, dryRun: false } });
  expect(restored.ok(), await restored.text()).toBeTruthy();
  const list = await (await page.request.get(`/api/projects/records?propertyId=${property.id}`)).json();
  expect(list.records.find((r: any) => r.title === "Restored dog stations").productUrl).toBe(record.productUrl);
  const unsafe = await page.request.patch(`/api/projects/records/${record.id}`, { headers, data: { productUrl: "javascript:alert(1)" } });
  expect(unsafe.status()).toBe(400);
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: testInfo.outputPath(`simple-project-${width}.png`), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(2);
  }
});

