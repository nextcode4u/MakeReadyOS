test("Spanish simple project fields and compact navigation are available", async ({ page }) => {
  const login = await page.request.post("/api/auth/login", { data: { identifier: process.env.ADMIN_EMAIL || "admin@example.com", password: process.env.ADMIN_PASSWORD || "ChangeThisAdmin!23456" } });
  expect(login.ok()).toBeTruthy();
  await page.route("**/api/auth/me", async route => {
    const response = await route.fetch();
    const body = await response.json();
    await route.fulfill({ response, json: { ...body, user: { ...body.user, language: "es" } } });
  });
  await page.goto("/");
  await page.getByTestId("module-rail-projects").click();
  await page.getByTestId("projects-quick-capture-open").click();
  await expect(page.getByText("¿Qué se necesita?", { exact: true })).toBeVisible();
  await expect(page.getByText("Enlace del producto (opcional)", { exact: true })).toBeVisible();
  await expect(page.getByText("Total estimado ($, opcional)", { exact: true })).toBeVisible();
  await page.getByTestId("module-rail-lease-compliance").click();
  await expect(page.getByLabel("Vista de problemas", { exact: true })).toHaveValue("active");
  await page.getByTestId("module-rail-property-wiki").click();
  await expect(page.getByLabel("Explorar conocimiento")).toBeVisible();
});
