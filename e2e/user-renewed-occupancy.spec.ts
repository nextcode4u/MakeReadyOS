import { expect, test } from "@playwright/test";

test("occupied changes and full-report renewal review close unfinished turns without approval", async ({ page }, info) => {
  test.skip(!process.env.COMPOSE_PROJECT_NAME?.startsWith("makereadyos-e2e-"), "Disposable demo environment required");
  test.setTimeout(150000);
  const prefix = info.project.name === "user-mobile" ? "RENEW-M" : "RENEW-D";
  const manual = `${prefix}-1`, renewal = `${prefix}-2`, kept = `${prefix}-3`;
  const today = new Date().toISOString().slice(0, 10);
  const tab = async (name: string) => {
    if (await page.getByTestId("mobile-views-toggle").isVisible()) await page.getByTestId("mobile-views-toggle").click();
    if (name === "My Work") await page.getByTestId("tab-my-work").click();
    else await page.getByRole("tab", { name, exact: true }).click();
  };
  const open = async (unit: string) => {
    await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(unit);
    await page.getByTestId(`${info.project.name === "user-mobile" ? "mobile" : "item"}-details-${unit.toLowerCase()}`).click();
    await page.getByTestId("drawer-pane-all").click();
  };
  await page.goto("/");
  await page.getByTestId("login-email").fill(process.env.ADMIN_EMAIL!);
  await page.getByTestId("login-password").fill(process.env.ADMIN_PASSWORD!);
  await page.getByRole("button", { name: /sign in/i }).click();
  await page.getByTestId("property-filter").selectOption({ label: "DG · Demo Gardens" });
  await tab("Availability & Units");
  await page.getByTestId("availability-import-csv").fill(`unit,vacancyStatus,reportDate\n${manual},VACANT NOT LEASED NOT READY,${today}\n${renewal},NTV NOT LEASED,${today}\n${kept},NTV NOT LEASED,${today}`);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-submit").click();
  await expect(page.getByTestId("availability-import-last-import")).toContainText("3 turns created");
  await tab("Table");
  await open(manual);
  await page.getByTestId("drawer-field-assignedTech").selectOption("Default Admin");
  await expect(page.getByTestId("drawer-field-assignedTech")).toBeEnabled();
  await page.getByTestId("item-drawer-close").click();
  await tab("My Work");
  await expect(page.locator('[data-testid^="my-work-item-"]').filter({ hasText: manual })).toBeVisible();
  await tab("Table");
  await open(manual);
  await expect(page.getByTestId("drawer-field-completionStatus")).toHaveValue("No - final approval pending");
  await page.getByTestId("drawer-field-vacancyStatus").selectOption("OCCUPIED");
  await expect(page.getByTestId("drawer-field-vacancyStatus")).toHaveValue("OCCUPIED");
  await expect(page.getByTestId("drawer-field-completionStatus")).toHaveValue("No - final approval pending");
  await page.getByTestId("item-drawer-close").click();
  await expect(page.getByTestId(`${info.project.name === "user-mobile" ? "mobile" : "item"}-details-${manual.toLowerCase()}`)).toHaveCount(0);
  await tab("My Work");
  await expect(page.locator('[data-testid^="my-work-item-"]').filter({ hasText: manual })).toHaveCount(0);
  await tab("Availability & Units");
  await page.getByTestId("availability-import-csv").fill(`unit,vacancyStatus,reportDate\n${prefix}-4,VACANT NOT LEASED NOT READY,${today}`);
  await page.getByTestId("availability-full-report").check();
  await page.getByTestId("availability-import-submit").click();
  const review = page.getByTestId("availability-occupied-review");
  await expect(review).toContainText(renewal);
  await expect(review).toContainText(kept);
  await review.getByRole("checkbox", { name: new RegExp(renewal) }).check();
  page.on("dialog", dialog => dialog.accept());
  await review.getByRole("button", { name: "Continue import" }).click();
  await expect(page.getByTestId("availability-import-last-import")).toContainText("1 turns created");
  await page.reload();
  await tab("Table");
  await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(renewal);
  await expect(page.getByTestId(`${info.project.name === "user-mobile" ? "mobile" : "item"}-details-${renewal.toLowerCase()}`)).toHaveCount(0);
  await open(kept);
  await expect(page.getByTestId("drawer-field-vacancyStatus")).toHaveValue("NTV NOT LEASED");
  await page.getByTestId("item-drawer-close").click();
  await page.getByTestId("top-archive-mode").selectOption("occupied");
  await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(renewal);
  await expect(page.getByTestId("board-table-view")).toContainText(renewal);
  await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(manual);
  await expect(page.getByTestId("board-table-view")).toContainText(manual);
});
