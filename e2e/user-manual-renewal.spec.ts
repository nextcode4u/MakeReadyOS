import { expect, test } from "@playwright/test";

test("staff record renewal dates without completing repairs", async ({ page }, info) => {
  test.skip(!process.env.COMPOSE_PROJECT_NAME?.startsWith("makereadyos-e2e-"), "Disposable demo environment required");
  test.setTimeout(120000);
  const unit = info.project.name === "user-mobile" ? "LEASE-M" : "LEASE-D";
  const tab = async (name: string) => {
    if (await page.getByTestId("mobile-views-toggle").isVisible()) await page.getByTestId("mobile-views-toggle").click();
    await page.getByRole("tab", { name, exact: true }).click();
  };
  await page.goto("/");
  await page.getByTestId("login-email").fill(process.env.ADMIN_EMAIL!);
  await page.getByTestId("login-password").fill(process.env.ADMIN_PASSWORD!);
  await page.getByRole("button", { name: /sign in/i }).click();
  await page.getByTestId("property-filter").selectOption({ label: "DG · Demo Gardens" });
  await tab("Availability & Units");
  await page.getByTestId("availability-import-csv").fill(`unit,vacancyStatus,reportDate\n${unit},NTV NOT LEASED,${new Date().toISOString().slice(0, 10)}`);
  page.once("dialog", dialog => dialog.accept());
  await page.getByTestId("availability-import-submit").click();
  await expect(page.getByTestId("availability-import-last-import")).toContainText("1 turns created");
  await tab("Table");
  await page.getByRole("textbox", { name: "Search board items", exact: true }).fill(unit);
  const details = page.getByTestId(`${info.project.name === "user-mobile" ? "mobile" : "item"}-details-${unit.toLowerCase()}`);
  await details.click();
  await page.getByTestId("record-renewal").locator("summary").click();
  await expect(page.getByTestId("renewal-submit")).toBeDisabled();
  await page.getByTestId("renewal-confirm").check();
  await expect(page.getByTestId("renewal-submit")).toBeDisabled();
  await page.getByTestId("renewal-start").fill("2031-01-01");
  await page.getByTestId("renewal-end").fill("2030-12-31");
  await page.getByTestId("renewal-submit").click();
  await expect(page.getByTestId("record-renewal").getByRole("alert")).toContainText("Lease end must be on or after lease start");
  await page.getByTestId("renewal-end").fill("2031-12-31");
  await page.getByTestId("renewal-submit").scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("renewal-form.png") });
  await page.getByTestId("renewal-submit").click();
  await expect(page.getByTestId("item-drawer-close")).toHaveCount(0);
  await expect(details).toHaveCount(0);
  await page.getByTestId("top-archive-mode").selectOption("occupied");
  await expect(page.getByTestId("board-table-view")).toContainText(unit);
  await page.reload();
  await tab("Availability & Units");
  await page.getByTestId("inventory-tab-directory").click();
  await page.getByTestId("unit-import-property").selectOption({ label: "DG - Demo Gardens" });
  await page.getByTestId("unit-import-csv").fill(`unit,currentResidentLeaseStartDate,currentResidentLeaseEndDate\n${unit},,`);
  const preview = page.getByTestId("unit-import-resident-preview");
  await expect(preview).toContainText("2031-01-01 (preserved)");
  await expect(preview).toContainText("2031-12-31 (preserved)");
});
