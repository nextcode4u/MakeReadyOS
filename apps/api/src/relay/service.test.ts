import test from "node:test";
import assert from "node:assert/strict";
import { createRelay, enrollTenant, openRelayDatabase, rotateTenant } from "./service.js";

test("relay verifies device possession, isolates tenants, expires registrations and revokes credentials", async t => {
  const db = openRelayDatabase(":memory:");
  const a = enrollTenant(db, "https://a.example.test"), b = enrollTenant(db, "https://b.example.test");
  let now = 1000000;
  const messages: Array<{ token: string; data: Record<string, string>; challenge: boolean }> = [];
  const app = createRelay(db, "test-project", async (token, data, challenge) => { messages.push({ token, data, challenge }); }, () => now);
  t.after(async () => { await app.close(); db.close(); });
  const post = (path: string, payload: unknown, credential = a.credential) => app.inject({ method: "POST", url: "/v1/" + path, headers: { authorization: "Bearer " + credential }, payload: payload as object });
  const input = { token: "synthetic-device-token-123", bindingId: "d673a280-1ae9-4f6d-8455-464921bc3431", sessionKey: "a".repeat(64), projectId: "test-project", expiresAt: now + 600000 };
  const begin = { ...input, nonce: "d673a280-1ae9-4f6d-8455-464921bc3432" };
  assert.equal((await post("challenge", begin, "b".repeat(64))).statusCode, 401);
  assert.equal((await post("challenge", { ...begin, projectId: "wrong-project" })).statusCode, 400);
  const challenge = await post("challenge", begin);
  assert.equal(challenge.statusCode, 200, challenge.body);
  assert.equal(messages[0].data.origin, "https://a.example.test");
  assert.equal(messages[0].challenge, true);
  assert.equal(challenge.body.includes(messages[0].data.proof), false);
  const confirmation = { ...input, challengeId: challenge.json().challengeId, proof: messages[0].data.proof };
  assert.equal((await post("confirm", { ...confirmation, proof: "0".repeat(64) })).statusCode, 409);
  assert.equal((await post("confirm", confirmation, b.credential)).statusCode, 409);
  assert.equal((await post("confirm", { ...confirmation, sessionKey: "b".repeat(64) })).statusCode, 409);
  const registered = await post("confirm", confirmation);
  assert.equal(registered.statusCode, 200, registered.body);
  assert.equal((await post("confirm", confirmation)).statusCode, 409);
  const send = { handle: registered.json().handle, notificationId: "event_123", expiresAt: now + 300000 };
  assert.equal((await post("send", send, b.credential)).statusCode, 410);
  assert.equal((await post("send", { ...send, title: "untrusted content" })).statusCode, 400);
  assert.equal((await post("send", send)).statusCode, 200);
  assert.deepEqual(Object.keys(messages[1].data).sort(), ["bindingId", "expiresAt", "notificationId", "origin"]);
  await post("revoke", { handle: send.handle }, b.credential);
  assert.equal((await post("send", send)).statusCode, 200);
  const replacement = rotateTenant(db, a.id);
  assert.equal((await post("send", send)).statusCode, 401);
  assert.equal((await post("send", send, replacement)).statusCode, 200);
  now += 600001;
  assert.equal((await post("send", { ...send, expiresAt: now + 1000 }, replacement)).statusCode, 410);
  db.prepare("UPDATE tenants SET enabled=0 WHERE id=?").run(a.id);
  assert.equal((await post("challenge", { ...begin, expiresAt: now + 600000 }, replacement)).statusCode, 401);
});

test("relay bounds challenges, drops expired proofs and never leaks sender errors", async t => {
  const db = openRelayDatabase(":memory:");
  const a = enrollTenant(db, "https://example.test");
  let now = 1000000, fail = false;
  let proof = "";
  const app = createRelay(db, "test-project", async (_token, data) => { if (fail) throw new Error("private sender secret"); proof = data.proof; }, () => now);
  t.after(async () => { await app.close(); db.close(); });
  const post = (path: string, payload: object) => app.inject({ method: "POST", url: "/v1/" + path, headers: { authorization: "Bearer " + a.credential }, payload });
  const input = { token: "synthetic-device-token-123", bindingId: "d673a280-1ae9-4f6d-8455-464921bc3431", sessionKey: "a".repeat(64), projectId: "test-project", expiresAt: now + 600000 };
  const begin = { ...input, nonce: "d673a280-1ae9-4f6d-8455-464921bc3432" };
  const challenge = await post("challenge", begin);
  now += 120001;
  assert.equal((await post("confirm", { ...input, challengeId: challenge.json().challengeId, proof })).statusCode, 409);
  fail = true;
  const failed = await post("challenge", begin);
  assert.equal(failed.statusCode, 503); assert.equal(failed.body.includes("secret"), false);
  fail = false;
  await post("challenge", begin); await post("challenge", begin);
  assert.equal((await post("challenge", begin)).statusCode, 429);
});
